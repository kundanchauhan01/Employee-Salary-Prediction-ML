# --------------------------------------------------
# LOAD MODEL
# --------------------------------------------------
@st.cache_resource
def load_model():
    return joblib.load("salary_prediction_model.pkl")


model = load_model()


# --------------------------------------------------
# HERO SECTION
# --------------------------------------------------
st.markdown("""
<div class="hero">

<h1>💰 AI Salary Prediction</h1>

<p>
Machine Learning based Employee Salary Prediction
</p>

</div>
""", unsafe_allow_html=True)


# --------------------------------------------------
# EMPLOYEE DETAILS
# --------------------------------------------------
st.markdown(
    '<div class="section-title">👤 Employee Details</div>',
    unsafe_allow_html=True
)

col1, col2 = st.columns(2)

with col1:

    age = st.number_input(
        "Age",
        min_value=18,
        max_value=70,
        value=25
    )

    gender = st.selectbox(
        "Gender",
        ["Male", "Female", "Other"]
    )

    education = st.selectbox(
        "Education Level",
        [
            "High School",
            "Bachelor's Degree",
            "Master's Degree",
            "PhD"
        ]
    )


with col2:

    experience = st.number_input(
        "Years of Experience",
        min_value=0.0,
        max_value=40.0,
        value=2.0
    )

    job_title = st.text_input(
        "Job Title",
        value="Data Analyst",
        placeholder="Example: Data Analyst"
    )


# --------------------------------------------------
# PREDICTION BUTTON
# --------------------------------------------------
st.write("")

if st.button(
    "🚀 Predict Salary",
    use_container_width=True
):

    input_data = pd.DataFrame({
        "Age": [age],
        "Gender": [gender],
        "Education Level": [education],
        "Job Title": [job_title],
        "Years of Experience": [experience]
    })

    prediction = model.predict(input_data)[0]

    st.markdown(f"""
    <div class="result-box">

    <div class="result-title">
    💰 Estimated Annual Salary
    </div>

    <div class="result-salary">
    ₹{prediction:,.2f}
    </div>

    </div>
    """, unsafe_allow_html=True)

    st.success("Prediction completed successfully!")

    st.caption(
        "⚠️ This is an estimated salary generated by the machine learning model."
    )


